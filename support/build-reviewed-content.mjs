import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const baseline = JSON.parse(fs.readFileSync(path.join(root, 'support/review-baseline.json'), 'utf8'));
const result = {};
const report = [];
for (const filename of fs.readdirSync(path.join(root, 'support/reviewed-lessons')).filter(f => f.endsWith('.json')).sort()) {
  const reviewed = JSON.parse(fs.readFileSync(path.join(root, 'support/reviewed-lessons', filename), 'utf8'));
  if (reviewed.status !== 'reviewed') continue;
  const [, level, number] = reviewed.code.match(/^L([12])-(\d{2})$/);
  const index = (Number(level) - 1) * 50 + Number(number) - 1;
  const lesson = baseline.lessons[index];
  const replacement = reviewed.replacement ?? {};
  for (const field of Object.keys(replacement)) assert(['title','kicker','level','category','media'].includes(field), `${reviewed.code}: unexpected replacement field ${field}`);
  if (replacement.media) {
    assert(reviewed.replacementApproval, `${reviewed.code}: replacement approval missing`);
    assert(/^media\/level[12]\/l[12]-\d{2}-r\d{8}\.mp3$/.test(replacement.media.videoSrc));
    assert(fs.existsSync(path.join(root,'public',replacement.media.videoSrc)));
    assert(replacement.media.kind === 'audio' && replacement.media.duration > 180);
  }
  let full = reviewed.transcript ?? lesson.paragraphs.map(p => p.replace(/\[(\d+)\]/g, (_, n) => lesson.answers[Number(n) - 1])).join('\n\n');
  for (const {start, end} of reviewed.removeSpans ?? []) {
    assert.equal(full.split(start).length - 1, 1, `${reviewed.code}: removal start not unique`);
    const from = full.indexOf(start);
    const to = end === null ? full.length : full.indexOf(end, from + start.length);
    assert(to > from, `${reviewed.code}: removal end missing`);
    full = full.slice(0, from) + full.slice(to);
  }
  if (reviewed.unwrapLinks) full = full.replace(/\[([^\]]*)\]\(https?:\/\/[^)]+\)/g, '$1');
  for (const [before, after] of reviewed.textReplacements ?? []) {
    assert.equal(full.split(before).length - 1, 1, `${reviewed.code}: replacement must occur exactly once: ${before}`);
    full = full.replace(before, after);
  }
  if (reviewed.appendText) full += ` ${reviewed.appendText}`;
  assert(!/https?:\/\/|!\[|\]\(|\bImage \d+:|\bFILE -/.test(full), `${reviewed.code}: article markup/caption remains`);
  assert.equal(reviewed.gaps.length, level === '1' ? 25 : 40);
  let cursor = 0;
  const pieces = [];
  for (const [i, phrase] of reviewed.gaps.entries()) {
    const position = full.indexOf(phrase, cursor);
    assert(position >= cursor, `${reviewed.code}: missing/out-of-order gap ${i + 1}: ${phrase}`);
    assert(!/[\p{L}\p{N}]/u.test(full[position - 1] ?? ''), `${reviewed.code}: partial word before gap ${i + 1}`);
    assert(!/[\p{L}\p{N}]/u.test(full[position + phrase.length] ?? ''), `${reviewed.code}: partial word after gap ${i + 1}`);
    pieces.push(full.slice(cursor, position), `[${i + 1}]`);
    cursor = position + phrase.length;
  }
  pieces.push(full.slice(cursor));
  const paragraphs = pieces.join('').split(/\n\s*\n/).map(p => p.replace(/\s+/g, ' ').trim()).filter(Boolean);
  const reconstructed = paragraphs.join(' ').replace(/\[(\d+)\]/g, (_, n) => reviewed.gaps[Number(n) - 1]);
  assert.equal(reconstructed, full.replace(/\s+/g, ' ').trim(), `${reviewed.code}: round-trip failed`);
  assert.equal(reviewed.paraphrases.length, 10);
  for (const [phrase, paraphrase, explanation, start, end] of reviewed.paraphrases) {
    assert(full.toLowerCase().includes(phrase.toLowerCase()), `${reviewed.code}: paraphrase source absent: ${phrase}`);
    assert(phrase !== paraphrase && explanation.length > 10);
    assert(Number.isFinite(start) && end > start && end <= (replacement.media ?? lesson.media).duration + 2, `${reviewed.code}: replay range invalid`);
  }
  assert.equal(reviewed.vocabulary.length, 10);
  const revision = crypto.createHash('sha256').update(JSON.stringify(reviewed)).digest('hex').slice(0, 12);
  const acceptedVariants = reviewed.gaps.map(phrase => reviewed.acceptedVariants?.[phrase] ?? []);
  result[index] = { ...replacement, paragraphs, answers: reviewed.gaps, acceptedVariants, contentRevision: revision, ...(reviewed.contentNote ? {contentNote: reviewed.contentNote} : {}), paraphrases: reviewed.paraphrases,
    vocabulary: reviewed.vocabulary.map(([term, meaning, note]) => ({term, meaning, note})), signals: reviewed.signals ?? [] };
  report.push({code: reviewed.code, status: 'content-reviewed-build-validated', revision, gapCount: reviewed.gaps.length, issuesFixed: reviewed.issuesFixed});
}
fs.writeFileSync(path.join(root, 'app/reviewed-content.generated.ts'), `// Individually reviewed lessons only. Generated by support/build-reviewed-content.mjs.\nexport const reviewedContent = ${JSON.stringify(result, null, 2)};\n`);
fs.writeFileSync(path.join(root, 'support/review-status.json'), JSON.stringify({ reviewed: report, pending: 100 - report.length, note: 'Build validation is not proof of deployment. Unlisted lessons have not completed individual review.' }, null, 2) + '\n');
console.log(`Validated ${report.length}/100 individually reviewed lessons.`);
